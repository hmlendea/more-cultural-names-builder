using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

using NUnit.Framework;

namespace MoreCulturalNamesBuilder.ArchitectureTests
{
    internal static class RepositorySources
    {
        internal static readonly string Root = FindRoot();

        internal static readonly string[] ProjectNames =
        [
            "MoreCulturalNamesBuilder",
            "MoreCulturalNamesBuilder.ArchitectureTests",
            "MoreCulturalNamesBuilder.UnitTests"
        ];

        internal static readonly SyntaxTree[] Trees = LoadTrees();

        private static readonly Dictionary<string, CSharpCompilation> compilations = BuildCompilations();

        internal static SemanticModel GetSemanticModel(SyntaxTree tree) =>
            compilations[GetProjectName(tree.FilePath)].GetSemanticModel(tree);

        internal static string GetProjectName(string path) =>
            Path.GetRelativePath(Root, path).Split(Path.DirectorySeparatorChar)[0];

        internal static bool IsProduction(SyntaxTree tree) =>
            string.Equals(GetProjectName(tree.FilePath), ProjectNames[0], StringComparison.Ordinal);

        internal static string Describe(SyntaxNode node, string reason)
        {
            FileLinePositionSpan position = node.GetLocation().GetLineSpan();

            return $"{Path.GetRelativePath(Root, position.Path)}:{position.StartLinePosition.Line + 1}: {reason}";
        }

        private static string FindRoot()
        {
            DirectoryInfo? directory = new(AppContext.BaseDirectory);

            while (directory is not null)
            {
                if (File.Exists(Path.Combine(directory.FullName, "MoreCulturalNamesBuilder.slnx")))
                {
                    return directory.FullName;
                }

                directory = directory.Parent;
            }

            throw new DirectoryNotFoundException("Architecture tests require the repository sources and solution.");
        }

        private static SyntaxTree[] LoadTrees()
        {
            List<SyntaxTree> trees = [];

            foreach (string projectName in ProjectNames)
            {
                string directory = Path.Combine(Root, projectName);
                Assert.That(Directory.Exists(directory), $"Required source directory is missing: {directory}");
                string[] files = Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories)
                    .Where(IsHandwritten).Order(StringComparer.Ordinal).ToArray();
                Assert.That(files, Is.Not.Empty, $"No handwritten C# sources found in {directory}");
                trees.AddRange(files.Select(path => CSharpSyntaxTree.ParseText(
                    File.ReadAllText(path),
                    new CSharpParseOptions(LanguageVersion.Preview),
                    path)));
            }

            return trees.ToArray();
        }

        private static bool IsHandwritten(string path)
        {
            string[] segments = Path.GetRelativePath(Root, path).Split(Path.DirectorySeparatorChar);

            return !segments.Contains("bin", StringComparer.OrdinalIgnoreCase) &&
                !segments.Contains("obj", StringComparer.OrdinalIgnoreCase) &&
                !path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) &&
                !path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) &&
                !File.ReadLines(path).Take(2).Any(line => line.Contains("<auto-generated", StringComparison.Ordinal));
        }

        private static Dictionary<string, CSharpCompilation> BuildCompilations()
        {
            string? platformAssemblies = AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string;
            Assert.That(platformAssemblies, Is.Not.Null.And.Not.Empty, "Runtime assembly inventory is unavailable.");
            string[] paths = platformAssemblies!.Split(Path.PathSeparator)
                .Concat(Directory.GetFiles(AppContext.BaseDirectory, "*.dll"))
                .Distinct(StringComparer.Ordinal).ToArray();
            Dictionary<string, CSharpCompilation> projects = [];

            foreach (string projectName in ProjectNames)
            {
                IEnumerable<MetadataReference> references = paths
                    .Where(path => !string.Equals(Path.GetFileNameWithoutExtension(path), projectName))
                    .Select(path => MetadataReference.CreateFromFile(path));
                projects.Add(projectName, CSharpCompilation.Create(
                    projectName,
                    Trees.Where(tree => string.Equals(GetProjectName(tree.FilePath), projectName)),
                    references,
                    new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
                        .WithNullableContextOptions(NullableContextOptions.Enable)));
            }

            return projects;
        }
    }
}
